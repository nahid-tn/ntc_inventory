if (!function_exists('enToBn')) {
    function enToBn($text)
    {
        $map = [
            'a'=>'আ','b'=>'ব','c'=>'ক','d'=>'দ','e'=>'এ','f'=>'ফ','g'=>'গ',
            'h'=>'হ','i'=>'ই','j'=>'জ','k'=>'ক','l'=>'ল','m'=>'ম','n'=>'ন',
            'o'=>'ও','p'=>'প','q'=>'ক','r'=>'র','s'=>'স','t'=>'ত','u'=>'উ',
            'v'=>'ভ','w'=>'ও','x'=>'ক্স','y'=>'য়','z'=>'জ'
        ];

        return strtr(strtolower($text), $map);
    }
}